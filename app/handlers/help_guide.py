GUIDE_LABELS = [
    ("start", "С чего начать"),
    ("setup", "Настройка"),
    ("bot", "Работа через бота"),
    ("mini", "Mini App"),
    ("stock", "Склад"),
    ("people", "Сотрудники"),
    ("work", "Задания и смены"),
    ("control", "Качество и остатки"),
    ("reports", "Отчёты и исправления"),
]


def guide_keyboard(current: str = "start") -> InlineKeyboardMarkup:
    rows: list[list[InlineKeyboardButton]] = []
    row: list[InlineKeyboardButton] = []
    for key, label in GUIDE_LABELS:
        prefix = "✓ " if key == current else ""
        row.append(InlineKeyboardButton(text=prefix + label, callback_data=f"guide:{key}"))
        if len(row) == 2:
            rows.append(row)
            row = []
    if row:
        rows.append(row)
    rows.append([InlineKeyboardButton(text="В главное меню", callback_data="menu:main")])
    return InlineKeyboardMarkup(inline_keyboard=rows)


def _page(key: str) -> str:
    return GUIDE_PAGES.get(key, GUIDE_PAGES["start"])


@router.callback_query(F.data == "menu:help")
async def open_guide(callback: CallbackQuery) -> None:
    await safe_edit_text(callback.message, _page("start"), reply_markup=guide_keyboard("start"))
    await callback.answer()


@router.callback_query(F.data.startswith("guide:"))
async def open_guide_page(callback: CallbackQuery) -> None:
    key = (callback.data or "guide:start").split(":", 1)[1] or "start"
    await safe_edit_text(callback.message, _page(key), reply_markup=guide_keyboard(key))
    await callback.answer()


@router.message(F.text.lower().in_({"как пользоваться", "помощь", "инструкция"}))
async def guide_message(message: Message) -> None:
    await message.answer(_page("start"), reply_markup=guide_keyboard("start"))
